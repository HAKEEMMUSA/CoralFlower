# Leviathan: the owner's drum samples -> firmware/src/drum_smp.h (eng_drum.c plays them on a kit's lanes, cf_seqd.c
# sq_kit_smp). 44.1 kHz WAVs (16/24/32-bit or float, mono or stereo: the channels' mean), kept as they are: 16-bit,
# no resampling (the engine runs at 44.1 kHz), no trim.
#   python3 tools/trap/wav2smp.py NAME=FILE.wav ... > firmware/src/drum_smp.h
import sys
import numpy as np
from scipy.io import wavfile

print("/* The owner's data, not under the GPL grant unless they say so (LICENSING.md).")
print(" * Leviathan: the owner's drum samples, generated by tools/trap/wav2smp.py (16-bit, 44.1 kHz, mono). Included by")
print(" * eng_drum.c. */")
rows = []
for arg in sys.argv[1:]:
    name, path = arg.split("=", 1)
    fs, a = wavfile.read(path)
    if fs != 44100:
        raise SystemExit(f"{path}: {fs} Hz, not 44100")
    a = a.astype(np.float64)
    kind = wavfile.read(path)[1].dtype
    if kind.kind == "i":
        a /= float(2 ** (8 * kind.itemsize - 1))
    elif kind.kind == "u":
        a = (a - 128.0) / 128.0
    if a.ndim > 1:
        a = a.mean(1)
    q = np.clip(np.round(a * 32767), -32767, 32767).astype(int)
    sym = "DRUM_SMP_" + "".join(c if c.isalnum() else "_" for c in name.upper())
    print(f"static const int16_t {sym}[{len(q)}] = {{   /* {name}: {len(q)} samples, {len(q) / fs * 1000:.0f} ms */")
    for i in range(0, len(q), 14):
        print("    " + ", ".join(str(v) for v in q[i:i + 14]) + ",")
    print("};")
    rows.append((name, sym, len(q)))
print("typedef struct { const char *name; const int16_t *d; uint16_t n; } drum_smp_t;")
print("static const drum_smp_t DRUM_SMP[] = {")
for name, sym, n in rows:
    print(f'    {{"{name}", {sym}, {n}}},')
print("};")
print("#define DRUM_NSMP ((uint32_t)(sizeof DRUM_SMP / sizeof DRUM_SMP[0]))")
