# Leviathan: the owner's 808 MIDI files -> firmware/src/dm8_lines.h (the rhythm machine's 808 patterns, cf_drum.c).
#   python3 tools/trap/mid2lines.py DIR > firmware/src/dm8_lines.h
# DIR holds the files as the owner sent them ("..808_246.mid" .. "..808_298.mid"; the number after the last "_" picks
# the line, LINES below). Each MIDI is kept at its own ticks (96 a beat, as the sequencer's SQ_PPQN): every note's
# start and velocity; a note that starts while the one before still sounds at another pitch (in the file) is a slide into
# it (the 808's GLIDE). Played one-shot: each note sounds until the next starts (the event's length), as an 808 sample
# in FL Studio rings on. The notes are intervals over the
# line's root (its most frequent note): the 808 plays them over the bass the keys play. A file whose second half
# repeats its first is kept as the half. Needs mido (pip install mido).
import collections, glob, os, sys
import mido

# number -> name (9 letters at most: the rhythm machine's title), in the order the rhythm machine lists them
LINES = [
    ("246", "Short"), ("247", "LastSpinz"), ("248", "UseALot 1"), ("249", "UseALot 2"), ("250", "UseALot 3"),
    ("251", "Zay 1"), ("252", "MingoJugg"), ("253", "Zay 2"), ("254", "Louder 1"), ("255", "Louder 2"),
    ("256", "Jugg"), ("257", "Spinz 5"), ("258", "Spinz 6"), ("259", "Spinz 7"), ("260", "Spinz 8"),
    ("261", "Mingo"), ("262", "Goon"), ("263", "New Rack"),
    ("282", "Spinz 1"), ("283", "Spinz 2"), ("284", "SF RT"), ("285", "Forsaken"), ("286", "King"),
    ("287", "Bitcrush"), ("288", "OhMyGawd"), ("289", "LuhTwizz"), ("290", "Chase"), ("291", "Chichi"),
    ("294", "Quis"), ("295", "Spinz 3"), ("296", "Spinz 4"), ("297", "Bounce"), ("298", "Secret"),
]
PPQ = 96
BAR = 4 * PPQ


def notes_of(path):
    m = mido.MidiFile(path)
    if m.ticks_per_beat != PPQ:
        raise SystemExit(f"{path}: {m.ticks_per_beat} ticks a beat, not {PPQ}")
    bpm, out = 120.0, []
    for tr in m.tracks:                          # (every track: a file of two keeps both, one 808)
        t, on = 0, {}
        for msg in tr:
            t += msg.time
            if msg.type == "set_tempo":
                bpm = mido.tempo2bpm(msg.tempo)
            if msg.type == "note_on" and msg.velocity > 0:
                if msg.note in on:
                    s, v = on.pop(msg.note)
                    out.append([s, t - s, msg.note, v])
                on[msg.note] = (t, msg.velocity)
            elif msg.type in ("note_off", "note_on") and msg.note in on:
                s, v = on.pop(msg.note)
                out.append([s, t - s, msg.note, v])
    out.sort()
    return bpm, out


def line_of(path):
    bpm, ns = notes_of(path)
    end = max(s + d for s, d, _, _ in ns)
    bars = max(1, -(-end // BAR))
    if bars > 2 and bars % 2:
        bars += 1
    total = bars * BAR
    for i, n in enumerate(ns):                   # (no length: to the next note, two bars at most)
        if n[1] <= 0:
            nxt = next((m[0] for m in ns[i + 1:] if m[0] > n[0]), total)
            n[1] = max(1, min(nxt - n[0], 2 * BAR))
    root = collections.Counter(n for _, _, n, _ in ns).most_common()
    root = min(k for k, c in root if c == root[0][1])
    ev = []
    for i, (s, d, n, v) in enumerate(ns):
        slide = any(p[0] < s and p[0] + p[1] > s + 2 and p[2] != n for p in ns[:i])
        ev.append((s % total, min(d, 65535), n - root, v, slide))
    ev.sort()
    # one-shot, as the owner's FL Studio 808s ring (the sampler plays on, "cut itself"): a note sounds until the next
    # one starts, whatever its length in the file (Chase's are 6 ticks long); the 808's own decay ends a long one
    ev = [(t, (ev[(i + 1) % len(ev)][0] - t) % total or total, iv, v, sl) for i, (t, _, iv, v, sl) in enumerate(ev)]
    while bars % 2 == 0 and bars > 1:            # (the second half the first again: the half)
        h = bars * BAR // 2
        a = [e for e in ev if e[0] < h]
        b = [(e[0] - h,) + e[1:] for e in ev if e[0] >= h]
        if a != b:
            break
        ev, bars = a, bars // 2
    return round(bpm), bars, ev


def main():
    d = sys.argv[1]
    files = {os.path.basename(f).rsplit("_", 1)[-1][:3]: f for f in glob.glob(os.path.join(d, "*.mid"))}
    print("/* The owner's data, not under the GPL grant unless they say so (LICENSING.md).")
    print(" * Leviathan: the 808 patterns, generated by tools/trap/mid2lines.py from the owner's MIDI files (2026-10-30).")
    print(" * An event: its tick in the line (96 a beat), how long it sounds (to the next note: one-shot), its interval")
    print(" * over the line's root, its velocity (bit 7: a slide into it from the note sounding). Included by cf_drum.c. */")
    print("typedef struct { uint16_t t, len; int8_t iv; uint8_t vel; } dm8_ev_t;")
    print("typedef struct { const char *name; uint8_t bars, bpm; uint16_t n; const dm8_ev_t *ev; } dm8_line_t;")
    print("static const dm8_ev_t DM8_EV_RAGE[] = {{0, 768, 0, 110}};   /* (Rage: one hit every two bars) */")
    rows = [("Rage", 2, 180, 1, "DM8_EV_RAGE")]
    total = 1
    for num, name in LINES:
        bpm, bars, ev = line_of(files[num])
        sym = "DM8_EV_" + num
        print(f"static const dm8_ev_t {sym}[] = {{   /* {name}: {bars} bars, {bpm} BPM ({os.path.basename(files[num])}) */")
        for i in range(0, len(ev), 6):
            print("    " + " ".join(f"{{{t}, {l}, {iv}, {v | (128 if s else 0)}}}," for t, l, iv, v, s in ev[i:i + 6]))
        print("};")
        rows.append((name, bars, bpm, len(ev), sym))
        total += len(ev)
    print("static const dm8_line_t DM8_LINES[] = {")
    for name, bars, bpm, n, sym in rows:
        print(f'    {{"{name}", {bars}, {bpm}, {n}, {sym}}},')
    print("};")
    print("#define DM8_N ((uint32_t)(sizeof DM8_LINES / sizeof DM8_LINES[0]))")
    print("#define DL_RAGE 1u                       /* (a rhythm's line: DM8_LINES index + 1) */")
    print(f"/* the 808 patterns as rhythms (cf_drum.c DM_RHY, after Rage): 808 only, no drums; ids 0 .. {len(LINES) - 1} */")
    print("#define DM8_RHYTHMS \\")
    for i, (name, bars, bpm, n, sym) in enumerate(rows[1:]):
        print(f'    {{"{name}", {i}, 4, {bars}, DMK_XRAGE, 0, {bpm}, {{0}}, {{0}}, {i + 2}}},' + (" \\" if i < len(rows) - 2 else ""))
    print(f"/* {total} events in all */")


main()
